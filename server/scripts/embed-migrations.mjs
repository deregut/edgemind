// Embeds drizzle/*.sql into src/db/migrations.generated.ts so migrations can run
// on serverless runtimes without filesystem access (Netlify + Cloudflare).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8"));
const out = journal.entries.map((e) => {
  const sql = readFileSync(join(root, "drizzle", `${e.tag}.sql`), "utf8");
  const statements = sql.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean);
  return { tag: e.tag, hash: createHash("sha256").update(sql).digest("hex"), statements };
});
writeFileSync(
  join(root, "src/db/migrations.generated.ts"),
  "// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit.\n" +
    "export const MIGRATIONS: { tag: string; hash: string; statements: string[] }[] = " +
    JSON.stringify(out, null, 1) + ";\n",
);
console.log(`embedded ${out.length} migrations`);
